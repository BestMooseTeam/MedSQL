-- ---------------------------------------------------------------------------
-- GET /api/patients  (список всех пациентов)
-- ---------------------------------------------------------------------------
-- SELECT p."Id", p."Address", p."BirthDate", p."DistrictNumber", p."Email",
--        p."HasInsurance", p."Iin", p."Name", p."Phone"
-- FROM "Patients" AS p
-- ORDER BY p."Name"
--
-- Чем отличается от GET /api/patients/1:
-- здесь нет WHERE — база возвращает ВСЕ строки таблицы, и они едут в C# целиком.
-- У запроса по id есть WHERE по первичному ключу и LIMIT 1, поэтому база читает
-- ровно одну строку. На картотеке в 100 000 человек первый запрос тянет 100 000
-- строк; спасает только то, что список пагинируется на фронтенде.

-- ---------------------------------------------------------------------------
-- GET /api/patients/1  (один пациент)
-- ---------------------------------------------------------------------------
-- SELECT p."Id", p."Address", p."BirthDate", p."DistrictNumber", p."Email",
--        p."HasInsurance", p."Iin", p."Name", p."Phone"
-- FROM "Patients" AS p
-- WHERE p."Id" = @id
-- LIMIT 1
--
-- @id — параметр, а не подставленное в текст число: так EF Core защищается
-- от SQL-инъекций. LIMIT 1 говорит базе, что хватит одной строки.

-- ---------------------------------------------------------------------------
-- POST /api/patients  (создать пациента) — два запроса
-- ---------------------------------------------------------------------------
-- 1. Проверка, что ИИН не занят (это наш ValidateAsync, а не EF Core):
-- SELECT p."Id", p."Address", p."BirthDate", p."DistrictNumber", p."Email",
--        p."HasInsurance", p."Iin", p."Name", p."Phone"
-- FROM "Patients" AS p
-- WHERE p."Iin" = @patient_Iin AND p."Id" <> @id
-- LIMIT 1
--
-- 2. Сама вставка:
-- INSERT INTO "Patients" ("Address", "BirthDate", "DistrictNumber", "Email",
--                         "HasInsurance", "Iin", "Name", "Phone")
-- VALUES (@p0, @p1, @p2, @p3, @p4, @p5, @p6, @p7)
-- RETURNING "Id";
--
-- Как приложение узнаёт id, который выдала база:
-- в конце INSERT стоит RETURNING "Id". PostgreSQL возвращает выданный номер
-- прямо в ответ на вставку, EF Core записывает его в свойство patient.Id.
-- Поэтому Id = 0 из тела запроса не нужен и игнорируется: в списке столбцов
-- его вообще нет.

-- ---------------------------------------------------------------------------
-- PUT /api/patients/6  (изменить пациента)
-- ---------------------------------------------------------------------------
-- 1. Найти пациента:
-- SELECT ... FROM "Patients" AS p WHERE p."Id" = @id LIMIT 1
--
-- 2. Проверить ИИН другого пациента:
-- SELECT ... FROM "Patients" AS p WHERE p."Iin" = @patient_Iin AND p."Id" <> @id LIMIT 1
--
-- 3. Обновить ТОЛЬКО изменённые столбцы:
-- UPDATE "Patients" SET "Name" = @p0
-- WHERE "Id" = @p1;
--
-- Что именно сохраняется: EF Core помнит исходные значения объекта и сравнивает
-- с новыми. В SET попадают только те столбцы, которые реально поменялись.
-- Мы меняли одно поле (Name), поэтому в UPDATE одно поле, а не все восемь.
--
-- Будет ли UPDATE, если отправить те же данные? Нет. Проверено: PUT с теми же
-- данными вернул 200, но UPDATE в консоль не попал — EF Core увидел, что
-- менять нечего, и команду в базу не отправил (в логе только два SELECT).

-- ---------------------------------------------------------------------------
-- DELETE /api/patients/6  (удалить пациента)
-- ---------------------------------------------------------------------------
-- 1. Найти пациента:
-- SELECT ... FROM "Patients" AS p WHERE p."Id" = @id LIMIT 1
--
-- 2. Проверить, есть ли у него справки и записи (иначе база вернёт ошибку
--    внешнего ключа и клиент получит 500 вместо понятного 400):
-- SELECT count(*)::int FROM "Spravki" AS s WHERE s."PatientId" = @id
-- SELECT count(*)::int FROM "Appointments" AS a WHERE a."PatientId" = @id
--
-- 3. Само удаление:
-- DELETE FROM "Patients" WHERE "Id" = @p0;
--
-- Справки при этом НЕ удаляются: в миграции Init у внешних ключей стоит
-- ON DELETE RESTRICT, поэтому пациента со справками база просто не даст удалить.
-- Ошибку перехватывает проверка из пункта 2 и превращает в 400 с текстом.

