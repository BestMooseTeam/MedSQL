-- ---------------------------------------------------------------------------
-- GET /api/stats  (статистика, задание 6 шаг 4) — пять запросов
-- ---------------------------------------------------------------------------
-- 1. Разбивка по видам:
-- SELECT s."Name", count(*)::int AS "Count", COALESCE(sum(s."Price"), 0.0) AS "Total"
-- FROM "Spravki" AS s
-- GROUP BY s."Name"
--
-- 2. SELECT count(*)::int FROM "Patients" AS p
-- 3. SELECT count(*)::int FROM "Spravki" AS s
-- 4. SELECT COALESCE(sum(s."Price"), 0.0) FROM "Spravki" AS s
-- 5. SELECT count(*)::int FROM "Appointments" AS a
--
-- COUNT и SUM считает сама база, в C# приезжает уже готовое число, а не строки
-- таблицы. SQL-запросов ровно пять: каждый CountAsync/SumAsync — отдельный
-- запрос. Можно было бы уложиться в один, но на таком объёме это не важно.

